#!/usr/bin/env bash
set -euo pipefail

# Directory containing Doxygen XML files
XML_DIR="${1:-doxygen_output/xml}"

# Path to the file containing exclusion patterns (one per line)
EXCLUDE_FILE="${2:-exclude_patterns.txt}"

# List of known top-level namespaces to target for deduplication
KNOWN_NAMESPACES=("pulsar" "calibration" "Pulsar" "Calibration")

if [ ! -d "$XML_DIR" ]; then
  echo "[clean_xml] Error: Directory '$XML_DIR' does not exist."
  exit 1
fi

INDEX_FILE="$XML_DIR/index.xml"
if [ ! -f "$INDEX_FILE" ]; then
  echo "[clean_xml] Error: '$INDEX_FILE' not found."
  exit 1
fi

echo "[clean_xml] Scanning $XML_DIR for duplicates under target namespaces: ${KNOWN_NAMESPACES[*]}..."

REMOVED_COUNT=0

# Helper function to remove an XML file and its <compound> node from index.xml
remove_xml_and_index_entry() {
  local target_path="$1"
  local target_filename
  target_filename=$(basename "$target_path")
  local refid="${target_filename%.xml}"

  # 1. Remove file
  rm -f "$target_path"

  # 2. Strip corresponding <compound refid="..."> block from index.xml
  sed -i.bak "/<compound refid=\"$refid\"/,/<\/compound>/d" "$INDEX_FILE"

  echo "[clean_xml] Removed XML & index entry: $target_filename"
  REMOVED_COUNT=$((REMOVED_COUNT + 1))
}

# --- Phase 1: Namespace Deduplication ---
for ns in "${KNOWN_NAMESPACES[@]}"; do
  for ns_file in "$XML_DIR"/class"${ns}"_1_1*.xml "$XML_DIR"/class_"${ns}"_1_1*.xml; do
    [ -e "$ns_file" ] || continue

    filename=$(basename "$ns_file")
    curr_filename="$filename"

    while [[ "$curr_filename" == *"_1_1"* ]]; do
      suffix="${curr_filename#*_1_1}"

      if [[ "$suffix" == _* ]]; then
        candidate_filename="class$suffix"
      else
        candidate_filename="class_$suffix"
      fi

      candidate_path="$XML_DIR/$candidate_filename"

      if [ -f "$candidate_path" ] && [ "$candidate_path" != "$ns_file" ]; then
        remove_xml_and_index_entry "$candidate_path"
      fi

      curr_filename="$candidate_filename"
    done
  done
done

# --- Phase 2: Pattern Removal from File ---
if [ -f "$EXCLUDE_FILE" ]; then
  echo "[clean_xml] Reading exclusion patterns from $EXCLUDE_FILE..."

  # Read file line-by-line, skipping empty lines and comments (#)
  while IFS= read -r pattern || [ -n "$pattern" ]; do
    # Trim leading/trailing whitespace
    pattern=$(echo "$pattern" | sed -e 's/^[[:space:]]*//' -e 's/[[:space:]]*$//')

    # Skip empty lines or comment lines
    [[ -z "$pattern" || "$pattern" == \#* ]] && continue

    # Match files in XML_DIR matching the pattern
    for target_file in "$XML_DIR"/$pattern; do
      [ -e "$target_file" ] || continue
      remove_xml_and_index_entry "$target_file"
    done
  done < "$EXCLUDE_FILE"
else
  echo "[clean_xml] Warning: Exclusion file '$EXCLUDE_FILE' not found. Skipping Phase 2."
fi

# Clean up temporary backup file generated by sed
rm -f "$INDEX_FILE.bak"

echo "[clean_xml] Done. Removed $REMOVED_COUNT total XML file(s) and cleaned index.xml."

